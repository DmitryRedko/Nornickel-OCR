import re


def split_text_to_subsections(document, regex):
    """
    Разделение текста на заголовки, подзаголовки и текст с использованием регулярных выражений.
    
    :param document: dict, входной текстовый документ в формате JSON.
    :param regex: str, регулярное выражение для поиска подзаголовков.
    :return: dict, структурированный результат.
    """
    def process_section(text, pattern):
        matches = list(re.finditer(pattern, text))
        if not matches:
            return text.strip()

        subsections = {}
        for i, match in enumerate(matches):
            start = match.start()
            end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
            subtitle = match.group(0)

            subsection_text = text[start + len(subtitle):end].strip()
            subsections[subtitle] = subsection_text

        return subsections

    structured_result = {}
    for title, values in document.items():
        full_text = " ".join(values)
        subsections = process_section(full_text, regex)
        structured_result[title] = subsections if isinstance(subsections, dict) else {"Text": subsections}

    return structured_result


